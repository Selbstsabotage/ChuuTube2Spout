"""Licence texts for a release, read out of the installed packages.

    python collect_licenses.py LICENSES_DIR SITE_PACKAGES [NATIVE_NAME=URL ...]

The macOS counterpart of `setup.ps1 -Licenses`, run by `setup.sh --licenses`
(1.1: the first Mac app was built with an empty licenses/ folder). Same
output: licenses/<package>-<version>.txt from each package's own .dist-info,
and licenses/INVENTORY.md, which lists every package with the licence it
declares and where its text came from.

NATIVE_NAME=URL pairs name components that pip knows nothing about (libmpv,
Node.js, the Syphon framework). setup.sh fetches their texts into
LICENSES_DIR first; this script only lists them, and says if one is missing.

A package whose wheel has no licence text, or not the right one, gets its text
from the project instead: setup.sh saves it as licenses/<package>.txt (see
PACKAGE_LICENSES there), and this script lists it next to the wheel's.

Plain standard library, so it runs with any Python 3.10+.
"""

from __future__ import annotations

import datetime
import re
import sys
from pathlib import Path

_TEXT_NAMES = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE)", re.I)


def native_file(name: str) -> str:
    """The file name a native component's text is saved under."""
    return re.sub(r"[^A-Za-z0-9._-]", "-", name) + ".txt"


def read_dist(dist_info: Path) -> dict | None:
    """Name, version, declared licence and text of one installed package."""
    meta = dist_info / "METADATA"
    if not meta.is_file():
        return None
    lines = meta.read_text(encoding="utf-8", errors="replace").splitlines()

    def field(key: str) -> str:
        for line in lines:
            if line.startswith(key + ":"):
                return line[len(key) + 1:].strip()
            if not line.strip():
                break                      # the headers end at the first blank
        return ""

    expression = field("License-Expression")
    if not expression:
        bare = field("License")
        if bare and len(bare) < 80:
            expression = bare
    classifiers = [line[len("Classifier: License :: "):]
                   for line in lines
                   if line.startswith("Classifier: License :: ")]

    # PEP 639 wheels keep the texts under .dist-info/licenses/; older ones
    # put a LICENSE beside METADATA. Some ship none - worth knowing, so it is
    # reported rather than papered over.
    candidates = []
    sub = dist_info / "licenses"
    if sub.is_dir():
        candidates += sorted(p for p in sub.rglob("*") if p.is_file())
    candidates += sorted(p for p in dist_info.iterdir()
                         if p.is_file() and _TEXT_NAMES.match(p.name))
    text = "\n\n".join(
        f"===== {p.name} =====\n" + p.read_text(encoding="utf-8", errors="replace")
        for p in candidates) or None
    return {"name": field("Name"), "version": field("Version"),
            "expression": expression, "classifiers": classifiers, "text": text}


def collect(licenses: Path, site_packages: Path,
            native: list[tuple[str, str]], today: str | None = None) -> dict:
    """Write the texts and INVENTORY.md. Returns what it found."""
    licenses.mkdir(parents=True, exist_ok=True)
    rows, missing, by_hand = [], [], []
    for dist in sorted(site_packages.glob("*.dist-info")):
        info = read_dist(dist)
        if not info or not info["name"]:
            continue
        declared = (info["expression"] or "; ".join(info["classifiers"])
                    or "NOT DECLARED")
        files = []
        if info["text"]:
            files.append(f"{info['name']}-{info['version']}.txt")
            (licenses / files[0]).write_text(info["text"], encoding="utf-8")
        # A text from the project itself, saved by setup.sh. Listed even when
        # the wheel has one: the PySide6 wheels for Windows carry only the Qt
        # commercial notice, not the LGPL they are used under (1.1).
        candidates = [f"{info['name']}.txt"]
        if not info["text"]:
            candidates.append(f"{info['name']}-{info['version']}.txt")
        for candidate in candidates:
            if (licenses / candidate).is_file():
                files.append(candidate)
                by_hand.append(candidate)
                break
        if not files:
            missing.append(f"{info['name']} {info['version']}")
        rows.append((info["name"], info["version"], declared, files))

    native_missing = [name for name, _url in native
                      if not (licenses / native_file(name)).is_file()]

    today = today or datetime.date.today().isoformat()
    out = ["# Licence inventory", "",
           f"Generated by `setup.sh --licenses` (macOS) on {today}.",
           "Read out of each package's own `.dist-info`, so the versions and the",
           "declared licences are the ones in this venv - not a hand-kept list.",
           "Re-run it whenever a dependency moves.", "",
           "| Package | Version | Declared licence | Text |", "|---|---|---|---|"]
    for name, version, declared, files in rows:
        shown = ", ".join(
            f"`{f}` (from the project)" if f in by_hand else f"`{f}`"
            for f in files) or "**none shipped**"
        out.append(f"| {name} | {version} | {declared} | {shown} |")
    if native:
        out += ["", "## Not from pip", "",
                "| Component | Text | Licence source |", "|---|---|---|"]
        for name, url in native:
            shown = ("**missing**" if name in native_missing
                     else f"`{native_file(name)}`")
            out.append(f"| {name} | {shown} | {url} |")
    if missing:
        out += ["", "## Shipped no licence text", "",
                "These declare a licence but carry no text, and none is in",
                "`licenses/` either. Add each to PACKAGE_LICENSES in setup.sh",
                "with the URL of its licence text, then run",
                "`bash setup.sh --licenses` again.", ""]
        out += [f"- {m}" for m in missing]
    (licenses / "INVENTORY.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    return {"packages": len(rows), "missing": missing, "by_hand": by_hand,
            "native_missing": native_missing}


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print(__doc__.strip().splitlines()[2].strip(), file=sys.stderr)
        return 2
    native = []
    for pair in argv[2:]:
        name, _, url = pair.partition("=")
        native.append((name, url))
    found = collect(Path(argv[0]), Path(argv[1]), native)
    print(f"==> licenses/ now holds {found['packages']} package licence(s) "
          "+ INVENTORY.md")
    if found["by_hand"]:
        print(f"==> {len(found['by_hand'])} text(s) came from the projects, "
              "not the wheels - listed")
    for what in found["missing"]:
        print(f"!!  shipped no licence text: {what} - see INVENTORY.md")
    for what in found["native_missing"]:
        print(f"!!  no licence text for {what} - see INVENTORY.md for where")
    return 1 if found["missing"] or found["native_missing"] else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
